-- Spendly Supabase database schema
-- Run in Supabase Dashboard → SQL Editor → New query.
-- Use only the anon/public key in Streamlit secrets, never service_role.

create table if not exists public.profiles (
    user_id uuid primary key references auth.users(id) on delete cascade,
    display_name text not null default 'Student',
    monthly_budget numeric(12,2) not null default 8000,
    budget_alerts boolean not null default true,
    updated_at timestamptz not null default now()
);

create table if not exists public.expenses (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    amount numeric(12,2) not null check (amount > 0),
    category text not null,
    description text not null,
    expense_date date not null default current_date,
    note text not null default '',
    created_at timestamptz not null default now()
);

create index if not exists expenses_user_date_idx
    on public.expenses(user_id, expense_date desc);

alter table public.profiles enable row level security;
alter table public.expenses enable row level security;

drop policy if exists "Users can read own profile" on public.profiles;
create policy "Users can read own profile" on public.profiles
    for select to authenticated using (auth.uid() = user_id);

drop policy if exists "Users can insert own profile" on public.profiles;
create policy "Users can insert own profile" on public.profiles
    for insert to authenticated with check (auth.uid() = user_id);

drop policy if exists "Users can update own profile" on public.profiles;
create policy "Users can update own profile" on public.profiles
    for update to authenticated using (auth.uid() = user_id)
    with check (auth.uid() = user_id);

drop policy if exists "Users can read own expenses" on public.expenses;
create policy "Users can read own expenses" on public.expenses
    for select to authenticated using (auth.uid() = user_id);

drop policy if exists "Users can insert own expenses" on public.expenses;
create policy "Users can insert own expenses" on public.expenses
    for insert to authenticated with check (auth.uid() = user_id);

drop policy if exists "Users can update own expenses" on public.expenses;
create policy "Users can update own expenses" on public.expenses
    for update to authenticated using (auth.uid() = user_id)
    with check (auth.uid() = user_id);

drop policy if exists "Users can delete own expenses" on public.expenses;
create policy "Users can delete own expenses" on public.expenses
    for delete to authenticated using (auth.uid() = user_id);
